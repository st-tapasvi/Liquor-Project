CREATE TRIGGER [TRG_SECURITY_QUESTION_LOCK_TEXT] ON [SECURITY_QUESTION]
AFTER UPDATE
AS
BEGIN
    SET NOCOUNT ON;
    IF EXISTS (
        SELECT 1
        FROM inserted i
        JOIN deleted d ON d.[ID] = i.[ID]
        WHERE CAST(i.[QUESTION_TEXT] AS VARBINARY(MAX)) <> CAST(d.[QUESTION_TEXT] AS VARBINARY(MAX))
          AND EXISTS (SELECT 1 FROM [USER_SECURITY_QUESTION] u WHERE u.[QUESTION_ID] = d.[ID]))
    BEGIN
        THROW 50000, 'Security question is in use: its text cannot change. Retire it (STATUS=0) and add a new one.', 1;
    END
END
GO
